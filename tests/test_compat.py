"""Backward-compatibility guard (PLAN.md ground rule 2).

Config files produced by v1.1.9 must keep loading in every later version. These
fixtures were generated by the shipped 1.1.9 code and must never be regenerated
— that is the whole point. When a later phase renames or reshapes a field, the
loader gains an alias and these tests keep passing.
"""

from pathlib import Path

import pytest

from vmctl.core.vmconfig import (
    DiskFormat,
    DiskVariant,
    NetworkType,
    StorageControllerType,
    VMConfig,
)
from vmctl.serializers.json_serializer import JSONSerializer
from vmctl.serializers.yaml_serializer import YAMLSerializer

CONFIGS = Path(__file__).parent / "fixtures" / "configs"
LEGACY = ["v1_1_9_multidisk", "v1_1_9_multinic"]


@pytest.mark.parametrize("stem", LEGACY)
def test_legacy_yaml_still_loads(stem):
    vm = YAMLSerializer().load(CONFIGS / f"{stem}.yaml")
    assert isinstance(vm, VMConfig)
    assert vm.name
    assert vm.cpu.count >= 1


@pytest.mark.parametrize("stem", LEGACY)
def test_legacy_json_still_loads(stem):
    vm = JSONSerializer().load(CONFIGS / f"{stem}.json")
    assert isinstance(vm, VMConfig)
    assert vm.name


@pytest.mark.parametrize("stem", LEGACY)
def test_legacy_yaml_and_json_describe_the_same_vm(stem):
    y = YAMLSerializer().load(CONFIGS / f"{stem}.yaml")
    j = JSONSerializer().load(CONFIGS / f"{stem}.json")
    assert YAMLSerializer().to_dict(y) == JSONSerializer().to_dict(j)


@pytest.mark.parametrize("stem", LEGACY)
def test_loading_and_saving_a_legacy_file_is_not_a_gratuitous_diff(stem, tmp_path):
    """Load/save must be a no-op, so upgrading vmctl does not churn Git."""
    original = (CONFIGS / f"{stem}.yaml").read_text()
    vm = YAMLSerializer().load(CONFIGS / f"{stem}.yaml")
    out = tmp_path / "again.yaml"
    YAMLSerializer().save(vm, out)
    assert out.read_text() == original


def test_legacy_field_values_are_understood():
    """Spot-check the 1.1.9 vocabulary that later phases must keep accepting."""
    vm = YAMLSerializer().load(CONFIGS / "v1_1_9_multidisk.yaml")
    assert vm.cpu.count == 8
    assert vm.memory.mb == 16384
    assert len(vm.disks) == 3
    formats = {d.format for d in vm.disks}
    assert formats == {DiskFormat.VDI, DiskFormat.VMDK, DiskFormat.VHD}
    assert DiskVariant.THICK in {d.variant for d in vm.disks}
    assert StorageControllerType.SAS in {sc.controller_type for sc in vm.storage_controllers}
    # The 1.1.9 default that later phases must treat as "unset" (F-01/M-06).
    assert all(d.controller_name for d in vm.disks)


def test_legacy_network_vocabulary_is_understood():
    vm = YAMLSerializer().load(CONFIGS / "v1_1_9_multinic.yaml")
    assert {n.network_type for n in vm.networks} == {
        NetworkType.BRIDGED,
        NetworkType.HOSTONLY,
        NetworkType.INTERNAL,
        NetworkType.NATNETWORK,
    }
    assert any(n.adapter_type == "virtio" for n in vm.networks)
